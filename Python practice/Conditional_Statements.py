#Understanding the conditional statements
#if statement
n=10
if n>0:
    print(f"{n} is a postive number")

#if-else statement
x=12
if x>0:
    print("Positive")
else:
    print("Not Positive")

#if-elif-else statement
n=int(input("enter a value: "))
if n>0:
    print("Positive")
elif n<0:
    print("Negative")
else:
    print("Neutral or Zero")

